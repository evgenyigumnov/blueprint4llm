import { parseAndValidateSvg } from '../svg/parse-and-validate.js';
import type { Element } from 'hast';

import { MAX_GRAPHVIZ_DIMENSION_PX, MAX_GRAPHVIZ_SVG_BYTES } from './graphviz-limits.js';

/** Removes only Viz.js's known inline-SVG comments and checks its safe dimensions. */
export function normalizeGraphvizSvg(svg: string): string {
  const sourceBytes = Buffer.byteLength(svg, 'utf8');
  if (sourceBytes > MAX_GRAPHVIZ_SVG_BYTES) {
    throw new Error(
      `Graphviz SVG is too large: ${sourceBytes} bytes (limit ${MAX_GRAPHVIZ_SVG_BYTES} bytes)`,
    );
  }

  let normalized = svg.trimStart();
  normalized = normalized.replace(/^<!-- Generated by graphviz version [\s\S]*?-->\s*/i, '');
  normalized = normalized.replace(/^<!-- (?:Title: [^\r\n]* )?Pages: \d+ -->\s*/i, '');
  if (/<\?xml-stylesheet\b/i.test(normalized)) {
    throw new Error('Graphviz SVG contains an external stylesheet reference');
  }
  if (/^\s*(?:<\?xml\b|<!doctype\b)/i.test(normalized)) {
    throw new Error('Graphviz inline SVG contains an unexpected XML wrapper');
  }

  const root = parseAndValidateSvg(normalized);
  validateDimensions(root);
  return normalized;
}

function validateDimensions(svg: Element): void {
  const width = parseSvgLength(svg.properties.width, 'width');
  const height = parseSvgLength(svg.properties.height, 'height');
  if (width > MAX_GRAPHVIZ_DIMENSION_PX || height > MAX_GRAPHVIZ_DIMENSION_PX) {
    throw new Error(`Graphviz SVG dimensions exceed ${MAX_GRAPHVIZ_DIMENSION_PX} px on one side`);
  }

  const viewBoxValue = svg.properties.viewBox ?? svg.properties.viewbox;
  if (typeof viewBoxValue !== 'string') {
    throw new Error('Graphviz SVG must contain a finite positive viewBox');
  }
  const values = viewBoxValue
    .trim()
    .split(/[\s,]+/)
    .map(Number);
  if (
    values.length !== 4 ||
    values.some((value) => !Number.isFinite(value)) ||
    values[2]! <= 0 ||
    values[3]! <= 0 ||
    !Number.isFinite(values[0]! + values[2]!) ||
    !Number.isFinite(values[1]! + values[3]!)
  ) {
    throw new Error('Graphviz SVG must contain a finite positive viewBox');
  }
}

function parseSvgLength(value: unknown, name: 'width' | 'height'): number {
  const text = typeof value === 'number' ? String(value) : value;
  if (typeof text !== 'string') {
    throw new Error(`Graphviz SVG must define a positive ${name}`);
  }
  const match = /^\s*(\d+(?:\.\d+)?|\.\d+)(px|pt|pc|mm|cm|in)?\s*$/i.exec(text);
  if (match === null) {
    throw new Error(`Graphviz SVG has an invalid ${name} dimension`);
  }

  const amount = Number(match[1]);
  const unit = (match[2] ?? 'px').toLowerCase();
  const factors: Record<string, number> = {
    px: 1,
    pt: 96 / 72,
    pc: 16,
    mm: 96 / 25.4,
    cm: 96 / 2.54,
    in: 96,
  };
  const pixels = amount * factors[unit]!;
  if (!Number.isFinite(pixels) || pixels <= 0) {
    throw new Error(`Graphviz SVG must define a finite positive ${name}`);
  }
  return pixels;
}
